"""
Реестр инструментов.

Инструмент — это функция приложения, которая не показывает статистику, а
что-то делает с рабочим окружением. Такие вещи не встраиваются ни в отчёты,
ни в мини-виджеты, поэтому у них своё меню и свой реестр.

Полноценная система плагинов здесь была бы инфраструктурой ради одной фичи:
расширения пишет тот же автор, а сборка PyInstaller плохо дружит с
динамической загрузкой модулей из папки. Поэтому — тот же приём, что и с
мини-виджетами (см. modules/widget/mini/registry.py): один декларативный
список, из которого UI строит меню, ничего не зная о конкретных инструментах.

Новый инструмент добавляется одной записью в TOOL_CLASSES. От класса нужно:
    key            — строковый идентификатор;
    title          — имя инструмента (заголовок группы в настройках);
    label          — подпись пункта меню;
    SETTINGS       — схема настроек (может быть пустой, см. ниже);
    __init__(root) — создаётся с корнем Tk;
    attach()       — подключиться (хуки, подписки);
    refresh()      — перечитать настройки после диалога настроек;
    detach()       — отключиться при выходе;
    menu_items()   — список (подпись, колбэк) для меню «Инструменты».

Формат `SETTINGS` — список настроек, каждая:
    {"key": имя параметра в config.py, "label": подпись, "kind": вид контрола}

Вид контрола задаёт `kind` (константы — в spec.py, отдельным модулем, чтобы
реестр и инструменты не импортировали друг друга по кругу):
    SETTING_BOOL (по умолчанию, можно не указывать) — галочка;
    SETTING_INT  — числовое поле; границы задают "from", "to", "step";
    SETTING_TEXT — строка; ширину задаёт "width".

Необязательные ключи: "hint" — серая подсказка справа от контрола;
"validate" — функция значения, возвращающая (заголовок, текст) ошибки или
None. Невалидное значение не сохраняется: диалог показывает ошибку и остаётся
открытым.

Схема описывает настройки декларативно ровно затем, зачем и у мини-виджетов
(см. modules/widget/mini/registry.py): диалог настроек рендерит вкладку
«Инструменты», пишет config.py и применяет значения в рантайме, не зная ни
одного конкретного инструмента.
"""

