"""
Версия приложения.

Схема — CalVer вида `ГОД.МЕСЯЦ.НОМЕР`:

* `ГОД`   — четыре цифры (2026);
* `МЕСЯЦ` — две цифры с ведущим нулём (08) — чтобы версии сортировались как строки;
* `НОМЕР` — порядковый номер релиза ВНУТРИ месяца, сбрасывается на 1 в начале
  каждого месяца.

`НОМЕР` считает релизы, а не фичи: любой выложенный билд (фича, фикс, рефакторинг)
увеличивает его на единицу. Это сделано намеренно — «фича или не фича» решается
на глаз, и две разные сборки могли бы получить одну версию. Что именно поменялось,
описывает CHANGELOG, а не номер.

Месяцы без релизов просто пропускаются: 2026.08.2 → 2026.10.1 — нормальная
последовательность.

Версии сравнивать через `version_tuple()`, а не как строки: при номере ≥ 10
строковое сравнение врёт ("2026.08.10" < "2026.08.9").
"""

__version__ = "2026.08.1"


def version_tuple(version: str = __version__) -> tuple[int, int, int]:
    """Версия как кортеж чисел — для корректного сравнения версий."""
    year, month, build = version.split(".")
    return int(year), int(month), int(build)
